from __future__ import annotations

import csv
from datetime import UTC, datetime
from io import BytesIO, StringIO
from typing import Any

from docx import Document
from openpyxl import Workbook
from sqlalchemy.orm import Session

from app.models import User
from app.services.evaluation_report import REPORT_VERSION, EvaluationReportService
from app.services.report_service import generate_member_evaluation_sheet_docx

MEMBER_EXPORT_COLUMNS = [
    "cycle_id",
    "member_evaluation_id",
    "mssv",
    "name",
    "unit_code",
    "role_title",
    "component_i_score",
    "component_ii_score",
    "component_iii_a_score",
    "component_iii_b_score",
    "total_score",
    "preliminary_classification",
    "final_classification",
    "attendance_rate",
    "blockers",
    "status",
    "appeal_count",
    "discipline_case_count",
]


class EvaluationExportService:
    def __init__(self, db: Session):
        self.db = db
        self.report_service = EvaluationReportService(db)

    def export_members_csv(
        self, cycle_id: str, filters: dict[str, Any] | None = None
    ) -> bytes:
        output = StringIO()
        writer = csv.DictWriter(output, fieldnames=MEMBER_EXPORT_COLUMNS)
        writer.writeheader()
        for row in self._normalized_member_rows(cycle_id, filters):
            writer.writerow(row)
        return output.getvalue().encode("utf-8-sig")

    def export_members_xlsx(
        self, cycle_id: str, filters: dict[str, Any] | None = None
    ) -> bytes:
        wb = Workbook()
        overview = wb.active
        overview.title = "Overview"
        dashboard = self.report_service.get_cycle_dashboard(cycle_id, filters)
        overview.append(["report_version", REPORT_VERSION])
        overview.append(["generated_at", datetime.now(UTC).isoformat()])
        for key in (
            "cycleCode",
            "cycleName",
            "status",
            "totalMembers",
            "computedMembers",
            "approvedMembers",
            "lockedMembers",
            "averageTotalScore",
        ):
            overview.append([key, dashboard.get(key)])

        members = wb.create_sheet("Members")
        members.append(MEMBER_EXPORT_COLUMNS)
        for row in self._normalized_member_rows(cycle_id, filters):
            members.append([row[column] for column in MEMBER_EXPORT_COLUMNS])

        self._append_breakdowns_sheet(wb, cycle_id, filters)
        self._append_list_sheet(wb, "Blockers", dashboard["riskSummary"].get("blockers", {}))
        self._append_appeals_sheet(wb, cycle_id, filters)
        self._append_discipline_cases_sheet(wb, cycle_id, filters)
        self._append_evidence_summary_sheet(wb, cycle_id, filters)

        stream = BytesIO()
        wb.save(stream)
        return stream.getvalue()

    def export_official_report_docx(
        self, cycle_id: str, *, actor: User, filters: dict[str, Any] | None = None
    ) -> bytes:
        dashboard = self.report_service.get_cycle_dashboard(cycle_id, filters)
        units = self.report_service.get_units_report(cycle_id, filters)["units"]
        doc = Document()
        doc.add_heading("Evaluation Official Report", 0)
        doc.add_paragraph(f"Cycle: {dashboard['cycleCode']} - {dashboard['cycleName']}")
        doc.add_paragraph(f"Status: {dashboard['status']}")
        doc.add_paragraph(f"Generated by: {actor.full_name} ({actor.username})")
        doc.add_paragraph(f"Generated at: {datetime.now(UTC).isoformat()}")
        doc.add_paragraph(f"Report version: {REPORT_VERSION}")

        doc.add_heading("Overview", level=1)
        table = doc.add_table(rows=1, cols=2)
        table.rows[0].cells[0].text = "Metric"
        table.rows[0].cells[1].text = "Value"
        for key in (
            "totalMembers",
            "computedMembers",
            "approvedMembers",
            "lockedMembers",
            "averageTotalScore",
            "openAppeals",
            "missingEvidenceEvents",
            "invalidWeightMembers",
        ):
            row = table.add_row().cells
            row[0].text = key
            row[1].text = str(dashboard.get(key))

        doc.add_heading("Classification Distribution", level=1)
        for key, value in dashboard["classificationDistribution"].items():
            doc.add_paragraph(f"{key}: {value}")

        doc.add_heading("Unit Summary", level=1)
        unit_table = doc.add_table(rows=1, cols=4)
        for idx, heading in enumerate(["Unit", "Members", "Average score", "Appeals"]):
            unit_table.rows[0].cells[idx].text = heading
        for unit in units:
            row = unit_table.add_row().cells
            row[0].text = unit["unitCode"]
            row[1].text = str(unit["totalMembers"])
            row[2].text = str(unit["averageTotalScore"])
            row[3].text = str(unit["appealCount"])

        doc.add_heading("Risk Summary", level=1)
        for key, value in dashboard["riskSummary"].items():
            doc.add_paragraph(f"{key}: {value}")

        stream = BytesIO()
        doc.save(stream)
        return stream.getvalue()

    def export_member_report_docx(
        self, cycle_id: str, member_id: str, *, actor: User
    ) -> bytes:
        report = self.report_service.get_member_report(cycle_id, member_id)
        stream = generate_member_evaluation_sheet_docx(report, actor=actor)
        return stream.getvalue()

    def _normalized_member_rows(
        self, cycle_id: str, filters: dict[str, Any] | None
    ) -> list[dict[str, Any]]:
        rows = self.report_service.get_member_export_rows(cycle_id, filters)
        return [
            {
                "cycle_id": row["cycleId"],
                "member_evaluation_id": row["memberEvaluationId"],
                "mssv": row["mssv"],
                "name": row["name"],
                "unit_code": row["unitCode"],
                "role_title": row["roleTitle"],
                "component_i_score": row["componentIScore"],
                "component_ii_score": row["componentIIScore"],
                "component_iii_a_score": row["componentIIIAScore"],
                "component_iii_b_score": row["componentIIIBScore"],
                "total_score": row["totalScore"],
                "preliminary_classification": row["preliminaryClassification"],
                "final_classification": row["finalClassification"],
                "attendance_rate": row["attendanceRate"],
                "blockers": ";".join(
                    str(item.get("code") if isinstance(item, dict) else item)
                    for item in row["blockers"]
                ),
                "status": row["status"],
                "appeal_count": row["appealCount"],
                "discipline_case_count": row["disciplineCaseCount"],
            }
            for row in rows
        ]

    def _append_breakdowns_sheet(
        self, wb: Workbook, cycle_id: str, filters: dict[str, Any] | None
    ) -> None:
        sheet = wb.create_sheet("Breakdowns")
        sheet.append(["mssv", "name", "criterion_code", "component", "final_score"])
        for row in self.report_service.get_member_export_rows(cycle_id, filters):
            report = self.report_service.get_member_report(cycle_id, row["memberId"])
            for breakdown in report["breakdowns"]:
                sheet.append(
                    [
                        row["mssv"],
                        row["name"],
                        breakdown["criterionCode"],
                        breakdown["component"],
                        breakdown["finalScore"],
                    ]
                )

    def _append_list_sheet(self, wb: Workbook, title: str, payload: dict[str, Any]) -> None:
        sheet = wb.create_sheet(title)
        sheet.append(["key", "value"])
        for key, value in payload.items():
            sheet.append([key, value])

    def _append_appeals_sheet(
        self, wb: Workbook, cycle_id: str, filters: dict[str, Any] | None
    ) -> None:
        sheet = wb.create_sheet("Appeals")
        sheet.append(["metric", "value"])
        report = self.report_service.get_appeal_report(cycle_id, filters)
        for key, value in report.items():
            if key != "cycleId":
                sheet.append([key, str(value)])

    def _append_discipline_cases_sheet(
        self, wb: Workbook, cycle_id: str, filters: dict[str, Any] | None
    ) -> None:
        sheet = wb.create_sheet("DisciplineCases")
        sheet.append(["member", "case_code", "case_type", "severity", "status", "blocker"])
        risk = self.report_service.get_risk_report(cycle_id, filters)
        member_lookup = {
            row["memberId"]: row["name"]
            for row in self.report_service.get_member_export_rows(cycle_id, filters)
        }
        for case in risk["disciplineCases"]:
            sheet.append(
                [
                    member_lookup.get(case.get("memberId"), ""),
                    case.get("caseCode"),
                    case.get("caseType"),
                    case.get("severity"),
                    case.get("status"),
                    case.get("blockerCode"),
                ]
            )

    def _append_evidence_summary_sheet(
        self, wb: Workbook, cycle_id: str, filters: dict[str, Any] | None
    ) -> None:
        sheet = wb.create_sheet("EvidenceSummary")
        sheet.append(["mssv", "name", "evidence_count"])
        for row in self.report_service.get_member_export_rows(cycle_id, filters):
            report = self.report_service.get_member_report(cycle_id, row["memberId"])
            sheet.append([row["mssv"], row["name"], len(report["evidence"])])
